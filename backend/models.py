"""
MockMate AI - Database Models
SQLAlchemy ORM models representing application entities: User, Interview, Question, Answer.
"""

from datetime import datetime, timezone
from sqlalchemy import Column, Integer, String, Text, Float, DateTime, ForeignKey
from sqlalchemy.orm import relationship
from database import Base


class User(Base):
    """
    User entity representing registered candidates.
    """
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    name = Column(String(100), nullable=False)
    email = Column(String(255), unique=True, index=True, nullable=False)
    hashed_password = Column(String(255), nullable=False)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationships
    interviews = relationship("Interview", back_populates="user", cascade="all, delete-orphan")

    def __repr__(self):
        return f"<User id={self.id} email='{self.email}' name='{self.name}'>"


class Interview(Base):
    """
    Interview session entity storing candidate configuration and progress.
    """
    __tablename__ = "interviews"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    role = Column(String(50), nullable=False)          # e.g. "Software Developer", "Data Analyst", "HR"
    language = Column(String(50), nullable=False)      # e.g. "English", "Tamil"
    status = Column(String(20), default="in_progress") # "in_progress", "completed"
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationships
    user = relationship("User", back_populates="interviews")
    questions = relationship("Question", back_populates="interview", cascade="all, delete-orphan", order_by="Question.question_number")
    answers = relationship("Answer", back_populates="interview", cascade="all, delete-orphan")

    def __repr__(self):
        return f"<Interview id={self.id} role='{self.role}' language='{self.language}'>"


class Question(Base):
    """
    Individual interview question entity generated by LLM.
    """
    __tablename__ = "questions"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    interview_id = Column(Integer, ForeignKey("interviews.id"), nullable=False)
    question_number = Column(Integer, nullable=False)
    category = Column(String(50), nullable=False)      # "technical" or "hr"
    question_text = Column(Text, nullable=False)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationships
    interview = relationship("Interview", back_populates="questions")
    answers = relationship("Answer", back_populates="question", cascade="all, delete-orphan")

    def __repr__(self):
        return f"<Question id={self.id} number={self.question_number} category='{self.category}'>"


class Answer(Base):
    """
    Candidate audio answer recorded per question, containing speech transcript,
    fluency metrics, LLM evaluation scores, and MediaPipe body language analytics.
    """
    __tablename__ = "answers"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    interview_id = Column(Integer, ForeignKey("interviews.id"), nullable=False)
    question_id = Column(Integer, ForeignKey("questions.id"), nullable=False)
    audio_file_path = Column(String(500), nullable=False)

    # Speech Analysis Metrics (Phase 5)
    transcript = Column(Text, nullable=True)
    duration_seconds = Column(Float, nullable=True, default=0.0)
    words_per_minute = Column(Float, nullable=True, default=0.0)
    filler_words_count = Column(Integer, nullable=True, default=0)
    filler_words_list = Column(Text, nullable=True, default="[]")  # JSON encoded list of detected fillers
    long_pauses_count = Column(Integer, nullable=True, default=0)   # Pauses > 2.0 seconds

    # LLM Answer Evaluation Fields (Phase 6)
    score_relevance = Column(Float, nullable=True, default=0.0)      # Out of 10
    score_structure = Column(Float, nullable=True, default=0.0)      # Out of 10
    score_depth = Column(Float, nullable=True, default=0.0)          # Out of 10
    score_communication = Column(Float, nullable=True, default=0.0)  # Out of 10
    score_overall = Column(Float, nullable=True, default=0.0)        # Out of 10
    strengths = Column(Text, nullable=True, default="[]")            # JSON encoded list of strengths
    weaknesses = Column(Text, nullable=True, default="[]")           # JSON encoded list of weaknesses
    improved_answer = Column(Text, nullable=True)                    # High-quality sample answer

    # Body Language Analysis Fields (Phase 7 - MediaPipe in Browser)
    eye_contact_pct = Column(Float, nullable=True, default=0.0)      # 0 to 100%
    head_tilt_pct = Column(Float, nullable=True, default=0.0)        # Stability / tilt score 0 to 100%
    smile_pct = Column(Float, nullable=True, default=0.0)            # 0 to 100%
    face_visible_pct = Column(Float, nullable=True, default=0.0)     # 0 to 100%

    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationships
    interview = relationship("Interview", back_populates="answers")
    question = relationship("Question", back_populates="answers")

    def __repr__(self):
        return f"<Answer id={self.id} int={self.interview_id} q={self.question_id} overall={self.score_overall} eye_contact={self.eye_contact_pct}%>"
